// SECOND CURSOR - NEXUS OS system font ("Nexus System 10").
//
// An original proportional bitmap UI font drawn for a 960x540 virtual screen.
// Every glyph is exactly GlyphHeight (10) rows tall; row 0 is the top row.
//
//   row 0 ....  cap height / ascender top ('t' starts on row 1)
//   row 1 ....
//   row 2 ....  x-height top (lowercase occupies rows 2-7)
//   row 3 ....
//   row 4 ....  '-', '+', '=' and '<' '>' are centred here
//   row 5 ....
//   row 6 ....
//   row 7 ....  last ink row above the baseline ('.' lives here)
//   ---------  baseline
//   row 8 ....  descenders (g j p q y , ;)
//   row 9 ....  descender bottom ('_' lives here)
//
// '#' = ink, '.' = empty. Glyph strings carry no blank side-bearing columns
// (apart from the space glyph); the renderer adds LetterSpacing between glyphs.
// Digits are all 5 px wide for tabular numbers. '0' carries a centre bar so it
// never reads as 'O', and 'I' (serifed) / 'l' (plain) / '1' (flag + foot) /
// '|' (full height) are all distinct.
//
// Pure data + measuring helpers: no UnityEngine reference (SecondCursor.Core).

