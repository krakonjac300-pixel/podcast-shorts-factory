        /// <summary>Every glyph has exactly this many rows. Row 0 is the top.</summary>
        public const int GlyphHeight = 10;

        /// <summary>Rows 0..7 sit above the baseline. Capitals and digits fill rows 0-7.</summary>
        public const int Ascent = 8;

        /// <summary>Lowercase x-height: rows 2-7.</summary>
        public const int XHeight = 6;

        /// <summary>Recommended distance between consecutive baselines, in pixels.</summary>
        public const int LineHeight = 12;

        /// <summary>Pen advance of a space, including the LetterSpacing that follows it.</summary>
        public const int SpaceAdvance = 3;

        /// <summary>Blank pixels the renderer inserts between two adjacent glyphs.</summary>
        public const int LetterSpacing = 1;

        /// <summary>
        /// Glyph bitmaps for printable ASCII (32-126). Each value is GlyphHeight strings of
        /// identical length (the glyph width); '#' is ink, '.' is empty.
        /// Treat the arrays as read-only.
        /// </summary>
        public static readonly IReadOnlyDictionary<char, string[]> Glyphs = BuildGlyphs();

        // Returned for any character that has no glyph (a hollow cap-height box).
        private static readonly string[] FallbackGlyph =
        {
            "#####",
            "#...#",
            "#...#",
            "#...#",
            "#...#",
            "#...#",
            "#...#",
            "#####",
            ".....",
            ".....",
        };

        /// <summary>Returns the glyph for <paramref name="c"/>, or a hollow box for unsupported characters.</summary>
        public static string[] GetGlyph(char c)
        {
            return Glyphs.TryGetValue(c, out string[] rows) ? rows : FallbackGlyph;
        }

        /// <summary>Width in pixels of the glyph for <paramref name="c"/> (SpaceAdvance - LetterSpacing for ' ').</summary>
        public static int GetWidth(char c)
        {
            if (c == ' ')
            {
                return SpaceAdvance - LetterSpacing;
            }

            return GetGlyph(c)[0].Length;
        }

        /// <summary>
        /// Width in pixels of a single line of text: the sum of glyph widths plus LetterSpacing
        /// between consecutive glyphs. Line breaks ('\n', '\r') are ignored.
        /// </summary>
        public static int MeasureWidth(string text)
        {
            if (string.IsNullOrEmpty(text))
            {
                return 0;
            }

            int width = 0;
            int glyphCount = 0;
            for (int i = 0; i < text.Length; i++)
            {
                char c = text[i];
                if (c == '\n' || c == '\r')
                {
                    continue;
                }

                if (glyphCount > 0)
                {
                    width += LetterSpacing;
                }

                width += GetWidth(c);
                glyphCount++;
            }

            return width;
        }

